const optionMatcher =
  (keys: readonly string[]) =>
  (_input: string, options: BoxOptions): boolean =>
    options !== null && keys.some((key) => options[key] !== undefined);

const DATA_CONVERTER_OPTION_KEYS = [
  'json',
  'tojson',
  'yaml',
  'yml',
  'toyaml',
  'toyml',
  'toml',
  'totoml',
  'xml',
  'toxml',
] as const;

const dataConverterOptionMatcher = optionMatcher(DATA_CONVERTER_OPTION_KEYS);
const certificateOptionMatcher = optionMatcher(['cert', 'certificate', 'ca']);
const base85OptionMatcher = optionMatcher([
  'base85',
  'base85encode',
  'base85decode',
  'ascii85',
]);
const durationOptionMatcher = optionMatcher([
  'duration',
  'humantime',
  'parseduration',
  'duration2s',
  'humanize',
]);
const timestampOptionMatcher = optionMatcher(['timestamp', 'unix', 'ts']);
const timestampCanHandle = (input: string, options: BoxOptions): boolean => {
  if (timestampOptionMatcher(input, options)) return true;

  const match = /^[+-]?(\d+)$/.exec(input.trim());
  if (!match) return false;
  const digits = match[1].replace(/^0+(?=\d)/, '');
  return digits.length >= 9 && digits.length <= 22;
};

const dataConverterCanHandle = (
  input: string,
  options: BoxOptions,
): boolean => {
  if (dataConverterOptionMatcher(input, options)) return true;

  const trimmed = input.trim();
  if (!trimmed) return false;
  if (
    (trimmed.startsWith('{') && trimmed.endsWith('}')) ||
    (trimmed.startsWith('[') && trimmed.endsWith(']')) ||
    hasXmlDocumentShape(trimmed)
  ) {
    return true;
  }

  return hasTomlDocumentShape(trimmed) || hasYamlDocumentShape(trimmed);
};

const certificateCanHandle = (input: string, options: BoxOptions): boolean =>
  certificateOptionMatcher(input, options) ||
  input.includes('-----BEGIN CERTIFICATE-----');

const mathCanHandle = (input: string, options: BoxOptions): boolean => {
  if (optionMatcher(['math'])(input, options)) return true;

  const trimmed = input.trim();
  if (parseDateString(trimmed) !== null) return false;
  if (/^\d+(?:-\d+){2,}$/.test(trimmed)) return false;
  if (/^\d+(?:\/\d+){2,}$/.test(trimmed)) return false;

  const shape = /[+\-*/^%!<>=&|]|[a-zA-Z]+\s*\(|\d+n\b|\d+\s*[a-zA-Z°]|\bto\b/;
  return (
    shape.test(trimmed) && (/\d/.test(trimmed) || /[<>=!&|]/.test(trimmed))
  );
};
const htmlEntityOptionMatcher = optionMatcher(['htmlencode', 'htmldecode']);
const htmlEntityCanHandle = (input: string, options: BoxOptions): boolean =>
  htmlEntityOptionMatcher(input, options) ||
  (input.length <= 100 * 1024 &&
    /&(?:#(?:[xX][\da-fA-F]+|\d+)|[a-zA-Z][a-zA-Z\d]*);/.test(input));
const httpStatusOptionMatcher = optionMatcher(['http']);
const httpStatusCanHandle = (input: string, options: BoxOptions): boolean =>
  httpStatusOptionMatcher(input, options) ||
  (input.length <= 256 &&
    /^(?:http|status)(?:\s+|:\s*)\d{3}$/i.test(input.trim()));

